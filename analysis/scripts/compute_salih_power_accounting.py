"""Compute the Salih et al. 2025 power-accounting comparison."""
from __future__ import annotations

import csv
import math
from pathlib import Path
from statistics import NormalDist

ROOT = Path(__file__).resolve().parents[2]
POOL = ROOT / "results/tables/14-cardiac-ladder/big_cohorts_pooled_all_v1.csv"
DILUTION = ROOT / "results/tables/14-cardiac-ladder/dilution.csv"
OUT_TABLE = ROOT / "results/tables/JBMR-salih-power-accounting_v1.csv"
OUT_REPORT = ROOT / "results/reports/JBMR-鍔熺巼瀵硅处_v1.md"

SALIH = {
    "AF": {"label": "Atrial fibrillation/flutter", "beta": 0.011, "se": 0.03},
    "HF": {"label": "Heart failure", "beta": 0.004, "se": 0.04},
    "NICM": {"label": "Non-ischaemic cardiomyopathy", "beta": 0.1, "se": 0.08},
}


def current_effects() -> dict[str, dict[str, float]]:
    out: dict[str, dict[str, float]] = {}
    with POOL.open(encoding="utf-8-sig", newline="") as fh:
        for row in csv.DictReader(fh):
            if row["endpoint"] in ("AF", "HF"):
                out[row["endpoint"]] = {
                    "beta": float(row["beta"]),
                    "se": float(row["se"]),
                    "p": float(row["p"]),
                    "i2": float(row["i2"]),
                }
    with DILUTION.open(encoding="utf-8-sig", newline="") as fh:
        for row in csv.DictReader(fh):
            if row["quantity"] == "non-ischaemic cardiomyopathy (measured)":
                out["NICM"] = {
                    "beta": float(row["b"]),
                    "se": float(row["se"]),
                    "p": float(row["p"]),
                    "i2": math.nan,
                }
    if set(out) != set(SALIH):
        raise RuntimeError(f"Missing current effects: {set(SALIH) - set(out)}")
    return out


def power(beta: float, se: float) -> float:
    nd = NormalDist()
    z = nd.inv_cdf(0.975)
    delta = abs(beta) / se
    return nd.cdf(-z - delta) + 1 - nd.cdf(z - delta)


def main() -> None:
    cur = current_effects()
    nd = NormalDist()
    mde_multiplier = nd.inv_cdf(0.975) + nd.inv_cdf(0.80)
    rows = []
    for key in ("AF", "HF", "NICM"):
        s, c = SALIH[key], cur[key]
        rows.append({
            "endpoint": key,
            "endpoint_label": s["label"],
            "salih_beta": s["beta"],
            "salih_se": s["se"],
            "salih_80pct_mde_abs_beta": mde_multiplier * s["se"],
            "current_beta": c["beta"],
            "current_se": c["se"],
            "current_p": c["p"],
            "current_i2": c["i2"],
            "power_at_current_beta_using_salih_se": power(c["beta"], s["se"]),
            "power_formula": "two-sided normal approximation, alpha=0.05",
            "source_salih": "DOI 10.1093/jbmrpl/ziaf037; PMID 40191156",
        })

    OUT_TABLE.parent.mkdir(parents=True, exist_ok=True)
    with OUT_TABLE.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    lines = [
        "> Copyright notice: This file was generated by the research-paper Skill system.",
        "> This is a pre-submission comparison draft and does not replace author confirmation.",
        "",
        "# JBMR power accounting against Salih et al. 2025",
        "",
        "## Purpose",
        "",
        "This comparison places the standard errors reported by Salih et al. 2025 beside the current pooled effects. It estimates the approximate power that Salih-level standard errors would provide for the current effect sizes. It is not a re-analysis of Salih's raw data and does not treat power as the only explanation for the difference.",
        "",
        "## Inputs and method",
        "",
        "- Salih et al. 2025: JBMR Plus 9(5):ziaf037; DOI [10.1093/jbmrpl/ziaf037](https://doi.org/10.1093/jbmrpl/ziaf037); PMID 40191156.",
        "- Salih exposure: trabecular BMD; 66,628 participants; 85 instruments, as reported in the current comparison record.",
        "- Current exposure: heel-ultrasound eBMD; harmonised analysis-file n=445,921; 600 instruments; sum R-squared=0.182; minimum F=23.4.",
        "- Current AF/HF effects: `results/tables/14-cardiac-ladder/big_cohorts_pooled_all_v1.csv`.",
        "- Current NICM effect: `results/tables/14-cardiac-ladder/dilution.csv`.",
        f"- Approximate 80% two-sided alpha=0.05 minimum detectable absolute effect: {mde_multiplier:.4f} times SE.",
        "- Approximate power: P(|N(beta/SE, 1)| > 1.96).",
        "",
        "## Results",
        "",
        "| Endpoint | Salih beta | Salih SE | Salih 80% MDE | Current beta | Current SE | Power at current beta using Salih SE |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        lines.append(
            f"| {r['endpoint_label']} | {r['salih_beta']:.3f} | {r['salih_se']:.3f} | "
            f"{r['salih_80pct_mde_abs_beta']:.3f} | {r['current_beta']:.3f} | "
            f"{r['current_se']:.3f} | {r['power_at_current_beta_using_salih_se']:.0%} |"
        )
    lines += [
        "",
        "## Interpretation boundary",
        "",
        "- Salih's reported SE values for AF, HF and NICM were 0.03, 0.04 and 0.08. Their approximate 80% detectable absolute effects were 0.084, 0.112 and 0.224.",
        "- At the current pooled effect sizes, those SE values provide approximately 56%, 15% and 24% power, respectively.",
        "- The studies also differ in bone phenotype, instrument architecture, outcome definitions, sample composition, sample overlap and replication structure. Power is therefore one quantified component of the comparison, not the sole explanation.",
        "- The manuscript should not call Salih's null findings wrong or claim that the present study simply disproves them. The accurate statement is that the studies have different detectable-effect ranges and are not design-equivalent.",
        "",
        "## Draft paragraph for JBMR Discussion",
        "",
        "> A previous two-sample MR study using a trabecular bone mineral density exposure reported no evidence of association with atrial fibrillation/flutter, heart failure, or non-ischaemic cardiomyopathy. Its reported standard errors were 0.03, 0.04, and 0.08, respectively, corresponding to approximate 80% power thresholds of 0.084, 0.112, and 0.224 on the log-odds scale. At the pooled effect sizes observed in the present study (-0.063 for atrial fibrillation, -0.037 for heart failure, and -0.101 for non-ischaemic cardiomyopathy), those standard errors would provide approximately 56%, 15%, and 24% power, respectively. The earlier null estimates therefore do not exclude effects of the magnitude observed here. The studies also differed in bone phenotype, instrument architecture, outcome definitions, sample composition, and replication structure, so the comparison is not a test of a single methodological change.",
        "",
        "## Status",
        "",
        "- This report and its CSV table were generated without changing the primary scientific conclusions.",
        "- The paragraph is a draft and has not yet been inserted into the formal JBMR manuscript.",
    ]
    OUT_REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT_TABLE.relative_to(ROOT)}")
    print(f"wrote {OUT_REPORT.relative_to(ROOT)}")
    for r in rows:
        print(r["endpoint"], f"power={r['power_at_current_beta_using_salih_se']:.6f}")


if __name__ == "__main__":
    main()

